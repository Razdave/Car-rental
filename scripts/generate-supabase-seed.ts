/**
 * Writes supabase/migrations/…_reference_data.sql (hubs, add-ons, promo codes) and
 * supabase/seed.sql (starter fleet) from src/data/cars.ts.  Run: npx tsx scripts/generate-supabase-seed.ts
 */
import { writeFileSync } from 'node:fs';
import { AVAILABLE_LOCATIONS, CARS_DATA, INITIAL_EXTRA_SERVICES } from '../src/data/cars.ts';

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (Array.isArray(v)) return `array[${v.map(q).join(', ')}]::text[]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const kind = (icon: string) => (icon === 'Plane' ? 'airport' : icon === 'Anchor' ? 'marina' : 'hub');

const reference = `-- Aurevon — reference data (generated by scripts/generate-supabase-seed.ts)
insert into public.locations (id, name, city, kind) values
${AVAILABLE_LOCATIONS.map((l) => `  (${q(l.id)}, ${q(l.name)}, ${q(l.city)}, ${q(kind(l.icon))})`).join(',\n')}
on conflict (id) do nothing;

insert into public.extra_services (id, name, description, price_per_day, icon, default_selected, sort) values
${INITIAL_EXTRA_SERVICES.map((s, i) => `  (${q(s.id)}, ${q(s.name)}, ${q(s.description)}, ${s.pricePerDay}, ${q(s.iconName)}, ${s.selected}, ${i})`).join(',\n')}
on conflict (id) do nothing;

insert into public.promo_codes (code, kind, value) values
  ('DRIVE20', 'percent', 20),
  ('VIP10', 'fixed', 50000)
on conflict (code) do nothing;
`;

const seed = `-- Aurevon — starter fleet (generated by scripts/generate-supabase-seed.ts). Safe to re-run.
insert into public.cars (id, name, brand, model, year, category, price_per_day, price_per_hour, power_hp, acceleration_0_100,
  top_speed_kmh, transmission, fuel_type, seats, doors, color, image_path, gallery_paths, description, features, rules,
  location, mileage_limit, host_name, host_rating, rating, review_count, is_available, is_popular, is_featured) values
${CARS_DATA.map((c) => `  (${[c.id, c.name, c.brand, c.model, c.year, c.category, c.pricePerDay, c.pricePerHour, c.powerHp, c.acceleration0to100,
  c.topSpeedKmH, c.transmission, c.fuelType, c.seats, c.doors, c.color, c.imageUrl, c.galleryImages, c.description, c.features, c.rules ?? [],
  c.location, c.mileageLimit, c.hostName, c.hostRating, c.rating, c.reviewCount, c.isAvailable, Boolean(c.isPopular), Boolean(c.isFeatured)].map(q).join(', ')})`).join(',\n')}
on conflict (id) do nothing;

-- Fixed-price packages (weekend specials, red-carpet/wedding blocks, weekly rates)
insert into public.rate_packages (id, car_id, name, description, duration_unit, duration, price, includes, pickup_days, active, sort) values
${CARS_DATA.flatMap((c) => (c.packages ?? []).map((p, i) => `  (${[p.id, c.id, p.name, p.description, p.durationUnit, p.duration, p.price, p.includes].map(q).join(', ')}, array[${p.pickupDays.join(', ')}]::int[], ${p.active}, ${i})`)).join(',\n')}
on conflict (id) do nothing;
`;

writeFileSync('supabase/migrations/20261120000005_reference_data.sql', reference);
writeFileSync('supabase/seed.sql', seed);
console.log('Wrote reference data migration and supabase/seed.sql');
